// Helper to create scheme object
function createScheme(id, name, govt, state, sector, desc, criteria, benefits, docs, link, ministry) {
  return {
    id,
    name,
    government: govt,
    state,
    sector,
    description: desc,
    eligibility: {
      criteriaText: criteria,
    },
    benefits,
    documents: docs,
    applicationMethod: "Online via National/State Citizen Portal or CSC (Common Service Centre)",
    officialSource: ministry,
    applicationLink: link
  };
}

